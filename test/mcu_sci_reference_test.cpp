namespace {
namespace reg = blofeld::hc12;
constexpr unsigned divisor = 60;
constexpr unsigned last_delay = 360;
constexpr unsigned ready = 0x20;
constexpr unsigned noise = 4;
constexpr unsigned framing = 2;
constexpr unsigned parity = 1;
constexpr unsigned first_word = 0x55;
constexpr unsigned second_word = 0xaa;
constexpr unsigned receive_interrupt_enable = 0x24;
constexpr unsigned receive_flags = 0x2f;
constexpr unsigned reset_status = 0xc0;

void require(const bool condition, const std::string &message) {
  if (!condition) { throw blofeld::Fault(message); }
}

void reject(const auto &operation) {
  try {
    operation();
  } catch (const blofeld::Fault &) { return; }
  throw blofeld::Fault("Expected invalid SCI reference operation to fail");
}

void advance(blofeld::McuSci &sci, const unsigned cycles, const bool level = true) {
  sci.advance({.bus_cycles = cycles, .receive_level = level});
}

blofeld::McuSci configured(const unsigned delay) {
  blofeld::McuSci sci;
  sci.set_receive_reference(
      blofeld::SciReceiveReference{.baud_divisor = divisor, .transfer_delay_bus_cycles = delay});
  sci.write({.address = reg::sci_baud_low, .value = divisor});
  sci.write({.address = reg::sci_control2, .value = receive_interrupt_enable});
  return sci;
}

struct Frame {
  unsigned word = 0;
  unsigned width = 8;
  std::uint8_t format = 0;
  bool stop = true;
  bool noisy = false;
  unsigned errors = 0;
};

void before_stop(blofeld::McuSci &sci, const Frame frame) {
  advance(sci, 3 * divisor);
  advance(sci, 16 * divisor, false);
  for (unsigned bit = 0; bit < frame.width; ++bit) {
    advance(sci, 16 * divisor, ((frame.word >> bit) & 1U) != 0);
  }
  advance(sci, 8 * divisor, frame.stop);
  advance(sci, divisor, frame.noisy ? !frame.stop : frame.stop);
  advance(sci, divisor - 1, frame.stop);
}

unsigned flags(blofeld::McuSci &sci) {
  return sci.read(reg::sci_status1) & receive_flags;
}

void check_transfer(blofeld::McuSci &sci, const Frame frame) {
  require(sci.interrupt_pending(), "The chosen transfer edge raises the enabled native request");
  constexpr unsigned byte_mask = 0xff;
  require(sci.read(reg::sci_data_low) == (frame.word & byte_mask),
          "Unarmed SCIDRL observes the independently supplied wire word");
  require(flags(sci) == (ready | frame.errors), "RDRF and frame errors share the declared edge");
  require(sci.read(reg::sci_data_high) == ((frame.word >> 1U) & 0x80U),
          "The received ninth slot reaches R8 independently of parity checking");
  static_cast<void>(sci.read(reg::sci_data_low));
  require(flags(sci) == 0 && !sci.interrupt_pending(),
          "Only observed status followed by SCIDRL acknowledges receive flags");
}

void test_each_bus_boundary_and_error_vector() {
  // Literal wire expectations, not frames generated by the SCI transmitter.
  constexpr std::array<Frame, 10> frames{
      {{},
       {.word = 0xff},
       {.word = 0x90},
       {.word = first_word},
       {.word = second_word},
       {.word = 7, .format = 2, .errors = parity},
       {.word = 0x107, .width = 9, .format = 0x12},
       {.word = 7, .width = 9, .format = 0x12, .errors = parity},
       {.word = 0x31, .noisy = true, .errors = noise},
       {.word = 0x42, .stop = false, .noisy = true, .errors = noise | framing}}};
  for (unsigned delay = 0; delay <= last_delay; ++delay) {
    for (const auto frame : frames) {
      auto sci = configured(delay);
      sci.write({.address = reg::sci_control1, .value = frame.format});
      before_stop(sci, frame);
      require(flags(sci) == 0 && !sci.interrupt_pending(),
              "Nothing is transferred one IPBus period before the RT10 majority");
      advance(sci, 1, frame.stop);
      if (delay != 0) {
        advance(sci, delay - 1, frame.stop);
        require(flags(sci) == 0 && !sci.interrupt_pending(),
                "Data/flags/request stay pending through the period before the chosen edge");
        advance(sci, 1, frame.stop);
      }
      check_transfer(sci, frame);
      advance(sci, last_delay - delay, frame.stop);
      require(flags(sci) == 0,
              "The end of the stop bit cannot transfer an acknowledged word twice");
      sci.set_receive_reference(std::nullopt);
      require(!sci.receive_reference(), "The strict model can be restored between complete frames");
    }
  }
}

void complete_frame(blofeld::McuSci &sci, const Frame frame) {
  before_stop(sci, frame);
  advance(sci, 1 + last_delay, frame.stop);
}

void test_overrun_and_acknowledgement_races() {
  for (unsigned delay = 1; delay <= last_delay; ++delay) {
    for (const bool acknowledge_before : {false, true}) {
      auto sci = configured(delay);
      complete_frame(sci, {.word = first_word});
      require(flags(sci) == ready, "The old unread word is present before the second frame");
      before_stop(sci, {.word = second_word, .stop = false});
      advance(sci, delay, false); // Decision plus delay-1.
      if (acknowledge_before) { static_cast<void>(sci.read(reg::sci_data_low)); }
      advance(sci, 1, false);
      require(sci.read(reg::sci_data_low) == (acknowledge_before ? second_word : first_word),
              "Overrun tests the live unread flag at transfer, preserving the old word if full");
      const auto expected = acknowledge_before ? ready | framing : 8U;
      require(flags(sci) == expected,
              "A newly unobserved OR/FE survives an older status-read acknowledgement");
      static_cast<void>(sci.read(reg::sci_data_low));
      advance(sci, last_delay - delay, false);
      complete_frame(sci, {.word = first_word});
      check_transfer(sci, {.word = first_word});
    }
  }
}

void test_back_to_back_and_snapshot_slices() {
  for (const unsigned delay : {0U, 1U, divisor - 1, divisor, divisor + 1, last_delay}) {
    auto sci = configured(delay);
    complete_frame(sci, {.word = first_word});
    check_transfer(sci, {.word = first_word});
    // No extra high mark before the second start bit.
    advance(sci, 16 * divisor, false);
    for (unsigned bit = 0; bit < 8; ++bit) {
      advance(sci, 16 * divisor, ((second_word >> bit) & 1U) != 0);
    }
    advance(sci, 10 * divisor);
    const auto frozen = sci;
    for (unsigned replay = 0; replay < 2; ++replay) {
      sci = frozen;
      // Exercise intra-sample deadline handling with only one-period slices.
      for (unsigned cycle = 0; cycle < last_delay; ++cycle) { advance(sci, 1); }
      require(flags(sci) == ready && sci.read(reg::sci_data_low) == second_word,
              "Back-to-back frames and a copied pending deadline replay the second literal word");
    }
  }
}

void test_fractional_divider_phase() {
  for (unsigned phase = 0; phase < divisor; ++phase) {
    for (const unsigned delay : {0U, 1U, divisor - 1, divisor, divisor + 1, last_delay}) {
      auto sci = configured(delay);
      advance(sci, (3 * divisor) + phase);
      advance(sci, 16 * divisor, false);
      constexpr unsigned word = 0x90;
      for (unsigned bit = 0; bit < 8; ++bit) {
        advance(sci, 16 * divisor, ((word >> bit) & 1U) != 0);
      }
      advance(sci, (10 * divisor) - phase - 1);
      require(flags(sci) == 0 && !sci.interrupt_pending(),
              "The native divider residue determines the first low sample and stop decision");
      advance(sci, 1);
      if (delay != 0) {
        advance(sci, delay - 1);
        require(flags(sci) == 0 && !sci.interrupt_pending(),
                "A sub-sample reference delay is measured from the actual native RT10 tick");
        advance(sci, 1);
      }
      check_transfer(sci, {.word = word});
      advance(sci, last_delay + phase - delay);
      sci.set_receive_reference(std::nullopt);
    }
  }
}

void test_pending_disable_and_unknown_pad() {
  auto sci = configured(1);
  before_stop(sci, {.word = first_word});
  advance(sci, 1);
  const auto frozen = sci;
  // A non-sampling IPBus deadline does not require an RX observation.
  sci.advance({.bus_cycles = 1});
  check_transfer(sci, {.word = first_word});
  sci = frozen;
  reject([&] { sci.advance({.bus_cycles = divisor}); });
  require(flags(sci) == 0, "An unknown sampled pad fails before advancing the pending transfer");
  sci.write({.address = reg::sci_control2, .value = 0});
  advance(sci, last_delay);
  require(flags(sci) == 0, "RE disable cancels the pending deadline without a ghost receive word");
  sci.write({.address = reg::sci_control2, .value = receive_interrupt_enable});
  complete_frame(sci, {.word = second_word});
  check_transfer(sci, {.word = second_word});
}

void test_reference_validation_and_reset() {
  blofeld::McuSci sci;
  for (const unsigned baud : {0U, 8192U}) {
    reject([&] { sci.set_receive_reference(blofeld::SciReceiveReference{.baud_divisor = baud}); });
  }
  reject([&] {
    sci.set_receive_reference(blofeld::SciReceiveReference{
        .baud_divisor = divisor, .transfer_delay_bus_cycles = last_delay + 1});
  });
  sci = configured(1);
  const auto reference = sci.receive_reference();
  advance(sci, 3 * divisor);
  advance(sci, divisor, false);
  reject([&] { sci.set_receive_reference(std::nullopt); });
  require(sci.receive_reference() == reference, "Rejected mid-frame selection preserves the model");
  sci.write({.address = reg::sci_control2, .value = 0});
  sci.set_receive_reference(std::nullopt);
  sci = configured(last_delay);
  before_stop(sci, {});
  advance(sci, 1);
  sci.reset();
  require(sci.receive_reference() ==
                  blofeld::SciReceiveReference{.baud_divisor = divisor,
                                               .transfer_delay_bus_cycles = last_delay} &&
              sci.read(reg::sci_status1) == reset_status && sci.read(reg::sci_control2) == 0,
          "Native reset aborts the pending transfer while retaining only reference context");
  sci.write({.address = reg::sci_control2, .value = 4});
  reject([&] { advance(sci, divisor); });
  require(sci.read(reg::sci_status1) == reset_status,
          "A native divisor mismatch fails before inventing a receive sample or flag");
  sci.write({.address = reg::sci_control2, .value = 0});
  sci.set_receive_reference(std::nullopt);
  sci.write({.address = reg::sci_baud_low, .value = divisor});
  sci.write({.address = reg::sci_control2, .value = receive_interrupt_enable});
  before_stop(sci, {});
  advance(sci, 1);
  reject([&] { static_cast<void>(sci.interrupt_pending()); });
  reject([&] { static_cast<void>(sci.read(reg::sci_status1)); });
  reject([&] { static_cast<void>(sci.read(reg::sci_data_high)); });
  reject([&] { static_cast<void>(sci.read(reg::sci_data_low)); });
}
}

int main() {
  try {
    test_each_bus_boundary_and_error_vector();
    test_overrun_and_acknowledgement_races();
    test_back_to_back_and_snapshot_slices();
    test_fractional_divider_phase();
    test_pending_disable_and_unknown_pad();
    test_reference_validation_and_reset();
    test_owned_sci_references();
    std::cout << "Explicit SCI reference phases, flags, races, snapshots and native WAI passed.\n";
    return 0;
  } catch (const std::exception &error) {
    std::cerr << error.what() << '\n';
    return 1;
  }
}
